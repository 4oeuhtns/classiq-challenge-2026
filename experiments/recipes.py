def _aligned_cube(bx, by, lx, ly):
    """The Cube pinning the top `lx` bits of x and `ly` bits of y.

    Geometrically that is one aligned block: 2^(6-lx) wide, 2^(6-ly) tall,
    positioned at (bx, by), which must be aligned to those sizes. Either count
    may be 0, giving a strip that spans the whole of that axis.

    Keep lx + ly <= MAX_CUBE_BITS. Every fixed bit is another input to the AND
    and another qubit of width.
    """
    return Cube.fix(x={b: (bx >> b) & 1 for b in range(COORD_BITS - lx, COORD_BITS)},
                    y={b: (by >> b) & 1 for b in range(COORD_BITS - ly, COORD_BITS)})


def _random_cube(rng):
    """An aligned Cube within the bit budget, placed anywhere legal."""
    lx = rng.randint(0, MAX_CUBE_BITS - 1)
    ly = rng.randint(1 if lx == 0 else 0, MAX_CUBE_BITS - lx)
    return _aligned_cube(rng.randrange(0, GRID_SIZE, GRID_SIZE >> lx) if lx else 0,
                         rng.randrange(0, GRID_SIZE, GRID_SIZE >> ly) if ly else 0,
                         lx, ly)


def _contained_halfplane(rng, lo=60, hi=400):
    """A half-plane covering between `lo` and `hi` pixels.

    Unbounded half-planes are useless here: one covering half the grid leaves
    a residual of ~2000 pixels and blows past MAX_TERMS. Clipping by area
    keeps the term affordable while still exercising the adder path.
    """
    for _ in range(200):
        a, b = rng.choice([(1, 1), (1, -1), (-1, 1), (-1, -1)])
        c = rng.randint(-120, 120)
        h = HalfPlane(a, b, c)
        if lo <= int(h.render().sum()) <= hi:
            return h
    return HalfPlane(1, 1, 20)


def _random_box(rng, lo=4, hi=28):
    s = rng.randint(lo, hi)
    t = rng.randint(lo, hi)
    x0 = rng.randrange(GRID_SIZE - s)
    y0 = rng.randrange(GRID_SIZE - t)
    return Rect(x0, x0 + s, y0, y0 + t)


def _snap_up(value, m):
    """Round an UPPER bound outward until its low m bits are 1s.

    `x <= 0b101111` is cheap because no matter what the low four bits of x
    are, the answer is already settled -- so the comparator never looks at
    them. ORing in the low bits is what creates that run of 1s.
    """
    return value | ((1 << m) - 1)


def _snap_down(value, m):
    """Round a LOWER bound outward until its low m bits are 0s.

    The mirror image: `x >= 0b100000` is cheap because trailing 0s settle a
    `>=` the same way trailing 1s settle a `<=`.
    """
    return value & ~((1 << m) - 1)


def _split(terms, prob, rng):
    """Cut some Rects in two. Identical pixels, more terms, more gates."""
    out = []
    for t in terms:
        if isinstance(t, Rect) and rng.random() < prob:
            if t.max_x > t.min_x and rng.random() < 0.5:
                m = rng.randrange(t.min_x, t.max_x)
                out += [Rect(t.min_x, m, t.min_y, t.max_y),
                        Rect(m + 1, t.max_x, t.min_y, t.max_y)]
                continue
            if t.max_y > t.min_y:
                m = rng.randrange(t.min_y, t.max_y)
                out += [Rect(t.min_x, t.max_x, t.min_y, m),
                        Rect(t.min_x, t.max_x, m + 1, t.max_y)]
                continue
        out.append(t)
    return out


# ---------------------------------------------------------------------------
# recipes -- each returns a complete, valid design
# ---------------------------------------------------------------------------

def r_greedy(rng):
    """Maximal rectangles. The efficient end of the range."""
    return patch(TARGET, "rect")


def r_rows(rng):
    """Horizontal runs: the baseline's own shape, one term per run."""
    return patch(TARGET, "row")


def r_cols(rng):
    """Vertical runs -- the same pixels as r_rows, transposed.

    x-ranges and y-ranges are not symmetric in cost, so these two should not
    land on the same depth. If they do, that is itself a finding.
    """
    return patch(TARGET, "col")


def r_cubes(rng):
    """Scatter aligned Cubes, then repair.

    Deliberately does not care whether a block lands on the logo -- one that
    does saves the patcher work, one that does not costs it.

    There is no recipe that covers the logo *well* with Cubes, because the
    logo is not power-of-two aligned: the stem spans x 2..26, which no
    aligned block matches. Cubes are here to be priced, not to win.
    """
    terms = [_random_cube(rng) for _ in range(rng.randint(1, 4))]
    return finish(terms, rng.choice(["rect", "rect", "row"]))


def r_boxfirst(rng):
    """Stamp random boxes, then repair.

    A box landing on the logo saves terms; one landing on white costs them.
    Pure spread, no cleverness.
    """
    return finish([_random_box(rng) for _ in range(rng.randint(1, 4))],
                  rng.choice(["rect", "rect", "row"]))


def r_split(rng):
    """A good cover, chopped up. Same mask, strictly more gates."""
    return _split(patch(TARGET, "rect"), rng.uniform(0.2, 0.9), rng)


def r_pixels(rng):
    """Patch one region pixel by pixel: the wasteful extreme of the range."""
    terms = patch(TARGET, "rect")
    keep = [t for t in terms if rng.random() > 0.25]
    return finish(keep, "pixel")


def r_parity_boxes(rng):
    """And(Rect, Parity): a plaid clipped to a box.

    Measured at 399 -- about the price of one plain Rect, for a far stranger
    mask. If the proxy can rank these correctly it has learned something real.
    """
    terms = [And((_random_box(rng, 6, 16),
                  Parity.fix(x=rng.sample(range(COORD_BITS), rng.randint(1, 2)))))
             for _ in range(rng.randint(1, 3))]
    return finish(terms, "rect")


def r_halfplane(rng):
    """One or two clipped half-planes, then repair.

    The only recipe that puts an adder in the circuit, and the only one that
    tests the plan's surprising measurement that a HalfPlane (265) is cheaper
    than a Rect (395).
    """
    return finish([_contained_halfplane(rng) for _ in range(rng.randint(1, 2))],
                  rng.choice(["rect", "row"]))


def r_redundant_and(rng):
    """Rewrite Rects as And(full-width strip, full-height strip).

    The intersection is the original rectangle exactly, so the mask is
    unchanged and the gate count is not. A term-counting proxy sees no
    difference at all -- which is the point.
    """
    terms = patch(TARGET, "rect")
    prob = rng.uniform(0.15, 0.5)
    out = []
    for t in terms:
        if isinstance(t, Rect) and rng.random() < prob:
            out.append(And((Rect(t.min_x, t.max_x, 0, GRID_SIZE - 1),
                            Rect(0, GRID_SIZE - 1, t.min_y, t.max_y))))
        else:
            out.append(t)
    return out


def r_nested_xor(rng):
    """Fold disjoint Rect pairs into a nested Xor.

    1732 depth where two plain terms cost 792, for identical pixels. Fewer
    terms, worse circuit: the cleanest possible counterexample to P1.
    """
    terms = patch(TARGET, "rect")
    rng.shuffle(terms)
    out, i, prob = [], 0, rng.uniform(0.3, 0.9)
    while i < len(terms):
        if i + 1 < len(terms) and rng.random() < prob:
            out.append(Xor((terms[i], terms[i + 1])))
            i += 2
        else:
            out.append(terms[i])
            i += 1
    return out


def r_not_pair(rng):
    """Replace R with [Not(R), FULL].

    ~R XOR everything is R again -- same mask, 839 plus a cheap rect instead
    of 395.
    """
    terms = patch(TARGET, "rect")
    budget = rng.randint(1, 3)
    out, used = [], 0
    for t in terms:
        if isinstance(t, Rect) and used < budget and rng.random() < 0.3:
            out += [Not(t), FULL]
            used += 1
        else:
            out.append(t)
    return out


def r_parity_noise(rng):
    """Append Parity pairs that cancel each other.

    Mask unchanged, term count up, depth barely moved -- a standalone Parity
    is a few Z gates and nothing else. The set needs designs where n_terms
    rises and cost does not, or a proxy could score well just by counting.
    """
    terms = patch(TARGET, "rect")
    for _ in range(rng.randint(1, 6)):
        p = Parity.fix(x=rng.sample(range(COORD_BITS), rng.randint(1, 3)),
                       y=rng.sample(range(COORD_BITS), rng.randint(0, 2)))
        terms += [p, p]
    return terms


def r_mixed(rng):
    """Several devices at once, which is what a real search result looks like."""
    terms = []
    if rng.random() < 0.6:
        terms.append(_contained_halfplane(rng))
    if rng.random() < 0.6:
        terms.append(And((_random_box(rng, 6, 16),
                          Parity.fix(x=rng.sample(range(COORD_BITS), 1)))))
    if rng.random() < 0.5:
        terms.append(_random_cube(rng))
    terms += [_random_box(rng) for _ in range(rng.randint(0, 2))]
    terms = finish(terms, rng.choice(["rect", "row"]))
    if rng.random() < 0.4:
        terms = _split(terms, rng.uniform(0.1, 0.4), rng)
    return terms


REFERENCE = {"greedy", "rows", "cols"}
"""Deterministic recipes: one design each, exempt from MAX_TERMS.

`cols` is 77 terms and would otherwise be resampled away -- but it is the
transpose of `rows` over the same pixels, and x-ranges and y-ranges do not
cost the same. Losing the pair would lose the cleanest test of that
asymmetry in the whole set.
"""

def r_aligned(rng):
    """Snap Rect bounds to power-of-two boundaries, then repair the overshoot.

    Measured 2026-09-13: a bound costs about 25 depth per bit the comparator
    has to examine, and a bound whose low bits are all 1s (upper) or all 0s
    (lower) hides those bits from it entirely. `x <= 31` costs 22 where
    `x <= 20` costs 185, and `Rect(32,47,16,31)` costs 47 where
    `Rect(5,40,12,33)` costs 398 -- 8.5x for the same shape, alignment alone.

    Alignment is per BOUND, not per rect: each of the four is priced
    independently, so snapping one of them is already worth ~100 depth.

    Snapping always grows the rect, so the overshoot falls into the residual
    and the patcher pays for it at roughly 400 depth a term. Whether the trade
    wins is genuinely open -- it depends on whether the overshoot lands on
    pixels something else already covers.

    This recipe exists because the logo's own rectangles are all arbitrarily
    aligned, so nothing in the rest of the calibration set varies in this
    feature. Without it the proxy's alignment term rides entirely on the
    sweep and is never tested against a real cover.
    """
    strength = rng.randint(1, 3)              # how many low bits to force
    chance = rng.uniform(0.3, 1.0)            # how many bounds to touch
    snapped = []
    for t in patch(TARGET, "rect"):
        snapped.append(Rect(
            _snap_down(t.min_x, strength) if rng.random() < chance else t.min_x,
            _snap_up(t.max_x, strength) if rng.random() < chance else t.max_x,
            _snap_down(t.min_y, strength) if rng.random() < chance else t.min_y,
            _snap_up(t.max_y, strength) if rng.random() < chance else t.max_y,
        ))
    return finish(snapped, rng.choice(["rect", "rect", "row"]))


RECIPES = [
    ("greedy", r_greedy), ("rows", r_rows), ("cols", r_cols),
    ("cubes", r_cubes), ("boxfirst", r_boxfirst), ("split", r_split),
    ("aligned", r_aligned),
    ("pixels", r_pixels), ("parity_boxes", r_parity_boxes),
    ("halfplane", r_halfplane), ("redundant_and", r_redundant_and),
    ("nested_xor", r_nested_xor), ("not_pair", r_not_pair),
    ("parity_noise", r_parity_noise), ("mixed", r_mixed),
]


# ---------------------------------------------------------------------------

def generate(n=300, seed=0, max_terms=MAX_TERMS):
    """Build `n` distinct valid designs, cycling through the recipes.

    Recipes are visited round-robin rather than sampled at random, so every
    one appears in proportion -- and so a batch that dies at 3 a.m. is still a
    balanced calibration set rather than four recipes explored and ten
    untouched.

    Args:
        n: how many designs to return.
        seed: seeds the Python RNG only; nothing here touches Classiq.
        max_terms: designs bigger than this are discarded and resampled.

    Returns:
        A list of (terms, tags) pairs. `tags` is [recipe_name] and goes
        straight into the log's `strategy_tags` field, so any row can be
        traced back to the recipe that produced it.

    Raises:
        AssertionError: if a recipe ever produces a design that does not draw
            the logo. That is a bug in this module, not a bad sample.
    """
    rng = random.Random(seed)
    out, seen, attempts = [], set(), 0
    while len(out) < n and attempts < n * 60:
        name, recipe = RECIPES[attempts % len(RECIPES)]
        attempts += 1
        terms = recipe(rng)
        assert matches_target(terms), f"recipe {name} produced an invalid cover"
        if not terms or (len(terms) > max_terms and name not in REFERENCE):
            continue
        fp = fingerprint(terms)
        if fp in seen:
            continue
        seen.add(fp)
        out.append((terms, [name]))
    return out


def _nesting(term):
    """Nesting depth of one term, counting the term itself as 1."""
    kids = getattr(term, "children", None)
    if kids is None:
        kids = [term.child] if hasattr(term, "child") else []
    return 1 + max((_nesting(k) for k in kids), default=0)


def describe(designs):
    """Print the spread. Run this before spending three hours on the batch."""
    import collections

    print(f"{len(designs)} designs\n")
    sizes = sorted(len(t) for t, _ in designs)
    print(f"terms per design : min {sizes[0]}  median {sizes[len(sizes) // 2]}  max {sizes[-1]}")
    kinds = collections.Counter()
    for terms, _ in designs:
        for t in terms:
            kinds[type(t).__name__] += 1
    print("term types       :", dict(kinds))
    print("max nesting      :", max(_nesting(t) for terms, _ in designs for t in terms))
    total = sum(len(t) for t, _ in designs)
    est = len(designs) * SECONDS_FIXED + total * SECONDS_PER_TERM
    print(f"rough batch time : {est / 3600:.1f} h"
          f"   ({total} terms total; mostly fixed overhead, so count matters most)")
    print()
    print(f"{'recipe':<16}{'n':>4}{'min':>7}{'med':>7}{'max':>7}")
    by = collections.defaultdict(list)
    for terms, tags in designs:
        by[tags[0]].append(len(terms))
    for name, _ in RECIPES:
        s = sorted(by[name])
        if s:
            print(f"{name:<16}{len(s):>4}{s[0]:>7}{s[len(s) // 2]:>7}{s[-1]:>7}")


if __name__ == "__main__":
    describe(generate(300, seed=0))
