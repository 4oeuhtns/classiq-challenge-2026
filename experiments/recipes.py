"""Calibration-set generator: many valid designs, spanning a wide cost range.

Phase 1 needs (design, real_depth) pairs to fit a proxy against. A proxy is
only as good as the spread of the set it was fitted on: if every design costs
about the same, a correlation over them measures nothing. So the job here is
not to produce *good* covers -- it is to produce covers whose costs differ as
much as possible, for reasons a proxy could in principle learn.

Two facts make every design valid by construction, so no cloud call is ever
spent on a cover that does not draw the logo:

1. Terms XOR. Given any partial cover, the pixels still wrong are exactly
   ``cover_mask(terms) ^ TARGET``. Adding terms covering precisely those
   pixels finishes the design, whatever nonsense came before.
2. ``patch`` always terminates: each rectangle it emits removes at least one
   wrong pixel and never touches a correct one.

So a recipe may lay down anything at all -- a half-plane, a plaid of parities,
a deliberately redundant AND -- and the patcher cleans up after it. An exotic
term that fits the logo well leaves little to patch and yields a cheap design;
one that fits badly leaves a lot and yields an expensive one. **The spread is
generated by how well the exotic terms happen to fit.**

Three recipes exist only to break the naive proxies, and they are the most
valuable designs in the set:

- ``nested_xor`` and ``not_pair`` encode the *same pixels* as a plain cover
  using measurably more gates (1732 vs 792, 839 vs 395). A proxy that counts
  terms cannot see the difference; one that understands structure can.
- ``parity_noise`` appends cancelling Parity pairs: term count climbs while
  depth barely moves, because a standalone Parity is a handful of Z gates.

Nothing here emits ``Or``. It was measured at 21 qubits against a budget of
18, so every such design would cost 30 s to be refused and contribute no
depth to fit against.

Cubes are capped at MAX_CUBE_BITS for the same reason -- see that constant.

    python experiments/recipes.py      # print the spread, make no cloud calls
"""

import pathlib
import random
import sys

import numpy as np

ROOT = next(p for p in [pathlib.Path(__file__).resolve(), *pathlib.Path(__file__).resolve().parents]
            if (p / "oracle").is_dir())
sys.path.insert(0, str(ROOT))

from oracle.mask import COORD_BITS, GRID_SIZE, TARGET
from oracle.terms import (And, Cube, HalfPlane, Not, Parity, Rect, Xor,
                          cover_mask, fingerprint, matches_target)

FULL = Rect(0, GRID_SIZE - 1, 0, GRID_SIZE - 1)
"""The whole grid. XORing it with a complement turns Not(R) back into R."""

MAX_TERMS = 60
"""Designs larger than this are resampled.

Not a correctness limit -- a time limit. Synthesis wall time grows with the
circuit, and an 80-term design costs the batch what four small ones would.
A few large designs give the correlation its dynamic range; a tail of them
just eats the night.
"""

MAX_CUBE_BITS = 4
"""Total fixed bits allowed in one Cube, across both axes.

Measured 2026-09-13: a Cube fixing 4 bits of x and 4 of y was refused, needing
**38 qubits** against a budget of 18. A Cube is not the free term it looks
like -- it is an AND over one comparison per fixed bit, and Classiq evaluates
all of them in parallel, so width grows with the bit count. The cheap Cube in
the log (part of a 146-depth design) fixes exactly one bit.

4 is a conservative guess at the safe ceiling, not a measured cliff. The cliff
between 4 and 8 bits is unmapped; each probe costs one refusal.
"""

SECONDS_FIXED = 38.0
SECONDS_PER_TERM = 0.9
"""Crude wall-time model: ``SECONDS_FIXED + SECONDS_PER_TERM * n_terms``.

Fitted by eye to four real calls (17 terms/44.6 s, 50/53.1, 77/113.5). Most of
the cost is fixed overhead, so a batch's length depends more on how many
designs it has than on how big they are. Used only to size the batch up front;
the runner's live ETA replaces it within a few minutes."""


# ---------------------------------------------------------------------------
# the patcher -- the primitive every recipe leans on
# ---------------------------------------------------------------------------

def _grow(mask, y0, x0, down=True, right=True):
    """Grow a maximal all-True rectangle from a seed pixel: right, then down."""
    x1 = x0
    if right:
        while x1 + 1 < GRID_SIZE and mask[y0, x1 + 1]:
            x1 += 1
    y1 = y0
    if down:
        while y1 + 1 < GRID_SIZE and mask[y1 + 1, x0:x1 + 1].all():
            y1 += 1
    return x1, y1


def patch(residual, mode="rect"):
    """Cover exactly the True pixels of `residual` with Rects.

    Args:
        residual: boolean mask of pixels the design currently gets wrong.
        mode: "rect" grows both ways (fewest terms), "row" emits horizontal
            runs, "col" emits vertical runs, "pixel" emits one Rect per pixel
            (most terms). The mode is the main dial for design size.

    Returns:
        A list of Rects whose XOR is exactly `residual`. They are disjoint, so
        their XOR is also their union.
    """
    r = np.array(residual, dtype=bool, copy=True)
    out = []
    while r.any():
        ys, xs = np.nonzero(r)
        y0, x0 = int(ys[0]), int(xs[0])
        if mode == "pixel":
            x1, y1 = x0, y0
        elif mode == "row":
            x1, y1 = _grow(r, y0, x0, down=False)
        elif mode == "col":
            y1 = y0
            while y1 + 1 < GRID_SIZE and r[y1 + 1, x0]:
                y1 += 1
            x1 = x0
        else:
            x1, y1 = _grow(r, y0, x0)
        out.append(Rect(x0, x1, y0, y1))
        r[y0:y1 + 1, x0:x1 + 1] = False
    return out


def finish(terms, mode="rect"):
    """Append whatever Rects make `terms` draw the logo exactly."""
    terms = list(terms)
    return terms + patch(cover_mask(terms) ^ TARGET, mode)


